#!/usr/bin/env node
// Copies the compiled ABIs and the recorded deployments into @perpes/evm so the
// off-chain services and the web app share one typed source of truth.
//   (cd contracts/evm && forge build) && pnpm --filter @perpes/evm abi
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, '../packages/evm/src/generated');
mkdirSync(outDir, { recursive: true });

const abiOf = (name) => JSON.parse(readFileSync(join(root, 'out', `${name}.sol`, `${name}.json`), 'utf8')).abi;

let abiTs = '// Generated by contracts/evm/script/export-abi.mjs — do not edit.\n\n';
for (const [name, exportName] of [
  ['PerpesEngine', 'perpesEngineAbi'],
  ['PerpesToken', 'perpesTokenAbi'],
  ['MockUSDC', 'mockUsdcAbi'],
  ['CounterflowVault', 'counterflowVaultAbi'],
]) {
  abiTs += `export const ${exportName} = ${JSON.stringify(abiOf(name), null, 2)} as const;\n\n`;
}
writeFileSync(join(outDir, 'abi.ts'), abiTs);

const deployments = {};
const files = readdirSync(join(root, 'deployments'));
for (const file of files) {
  // <chainId>.json only — <chainId>.uniswap.json / .upgrade-pending.json are read alongside.
  if (!/^\d+\.json$/.test(file) || file === '31337.json') continue;
  const d = JSON.parse(readFileSync(join(root, 'deployments', file), 'utf8'));
  const uniFile = `${d.chainId}.uniswap.json`;
  const uni = files.includes(uniFile) ? JSON.parse(readFileSync(join(root, 'deployments', uniFile), 'utf8')) : null;
  deployments[d.chainId] = {
    engine: d.engine.toLowerCase(),
    usdc: d.usdc.toLowerCase(),
    mockUsdc: Boolean(d.mockUsdc),
    deployBlock: Number(d.deployBlock),
    poolManager: uni ? uni.poolManager.toLowerCase() : null,
    positionManager: uni ? uni.positionManager.toLowerCase() : null,
    v3Factory: uni?.v3Factory ? uni.v3Factory.toLowerCase() : null,
    wmon: uni?.wmon ? uni.wmon.toLowerCase() : null,
    // Per-market Counterflow vaults are beacon proxies; each market's is engine.lpVault(token).
    counterflowBeacon: d.counterflowBeacon ? d.counterflowBeacon.toLowerCase() : null,
  };
}
writeFileSync(
  join(outDir, 'deployments.ts'),
  '// Generated by contracts/evm/script/export-abi.mjs — do not edit.\n\n' +
    `export const recordedDeployments: Record<number, { engine: \`0x\${string}\`; usdc: \`0x\${string}\`; mockUsdc: boolean; deployBlock: number; poolManager: \`0x\${string}\` | null; positionManager: \`0x\${string}\` | null; v3Factory: \`0x\${string}\` | null; wmon: \`0x\${string}\` | null; counterflowBeacon: \`0x\${string}\` | null }> = ${JSON.stringify(deployments, null, 2)};\n`,
);
console.log(`wrote ABIs and ${Object.keys(deployments).length} deployment(s) to ${outDir}`);
